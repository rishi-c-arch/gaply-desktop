/// The functions the frontend calls today. A new one fails the scan until it
/// is added to `FS_FUNCTIONS` with its command and permissions, and here.
const FUNCTIONS_IN_USE: &[&str] = &[
    "exists",
    "mkdir",
    "readFile",
    "remove",
    "writeFile",
    "writeTextFile",
];

/// Names a file may destructure from the module that are not commands.
const NOT_COMMANDS: &[&str] = &["BaseDirectory"];

fn strings_in(v: &serde_json::Value, out: &mut Vec<String>) {
    match v {
        serde_json::Value::String(s) => out.push(s.clone()),
        serde_json::Value::Array(a) => a.iter().for_each(|x| strings_in(x, out)),
        serde_json::Value::Object(m) => m.values().for_each(|x| strings_in(x, out)),
        _ => {}
    }
}

fn capability_permissions() -> Vec<String> {
    let dir = Path::new(ROOT).join("capabilities");
    let mut files = 0;
    let mut permissions = Vec::new();
    for e in std::fs::read_dir(&dir).unwrap() {
        let p = e.unwrap().path();
        if p.extension().is_some_and(|x| x == "json") {
            files += 1;
            let v: serde_json::Value =
                serde_json::from_str(&std::fs::read_to_string(&p).unwrap()).unwrap();
            strings_in(&v["permissions"], &mut permissions);
        }
    }
    assert!(
        files >= 1 && permissions.iter().any(|p| p.starts_with("fs:")),
        "{files} capability files and no fs permission: the scan is inert"
    );
    permissions
}

fn files_under(dir: &Path, out: &mut Vec<PathBuf>) {
    for e in std::fs::read_dir(dir).unwrap() {
        let p = e.unwrap().path();
        let name = p
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or("")
            .to_string();
        if p.is_dir() {
            files_under(&p, out);
        } else if [".ts", ".tsx", ".js", ".jsx"]
            .iter()
            .any(|x| name.ends_with(x))
            && !name.contains(".vitest.")
            && !name.contains(".test.")
        {
            out.push(p);
        }
    }
}

fn is_comment(line: &str) -> bool {
    let t = line.trim_start();
    t.starts_with("//") || t.starts_with('*') || t.starts_with("/*")
}

/// The names inside `{ ... }`, with `a: b` renames read as `a`.
fn names_in_braces(inner: &str) -> Vec<String> {
    inner
        .split(',')
        .map(|n| n.split(':').next().unwrap_or("").trim())
        .map(|n| n.strip_prefix("type ").unwrap_or(n).trim())
        .filter(|n| !n.is_empty())
        .map(str::to_string)
        .collect()
}

/// The plugin-fs names one file takes, from three single-line shapes:
/// `const { a, b } = await import('<module>')`, the same through an alias
/// `const fs = () => import('<module>')` as `= await fs()`, and a static
/// `import { a, b } from '<module>'`. Anything else yields nothing, and the
/// caller fails the file rather than passing it.
fn fs_names_in(text: &str) -> Vec<String> {
    let dynamic = [
        format!("import('{MODULE}')"),
        format!("import(\"{MODULE}\")"),
    ];
    let mut sources: Vec<String> = dynamic.to_vec();
    for line in text.lines().filter(|l| !is_comment(l)) {
        if dynamic.iter().any(|d| line.contains(&format!("=> {d}"))) {
            if let Some(rest) = line.trim_start().strip_prefix("const ") {
                let alias = rest.split('=').next().unwrap_or("").trim();
                if !alias.is_empty() {
                    sources.push(format!("{alias}()"));
                }
            }
        }
    }
    let mut names = Vec::new();
    for line in text.lines().filter(|l| !is_comment(l)) {
        if let Some(at) = line.find("} = await ") {
            let after = line[at + "} = await ".len()..].trim_start();
            if sources.iter().any(|s| after.starts_with(s.as_str())) {
                if let Some(open) = line[..at].rfind('{') {
                    names.extend(names_in_braces(&line[open + 1..at]));
                }
            }
        }
        let t = line.trim_start();
        if t.starts_with("import {")
            && (t.contains(&format!("from '{MODULE}'"))
                || t.contains(&format!("from \"{MODULE}\"")))
        {
            if let (Some(open), Some(close)) = (t.find('{'), t.find('}')) {
                names.extend(names_in_braces(&t[open + 1..close]));
            }
        }
    }
    names
}

/// Every frontend file that names the module, with the names it takes.
fn fs_uses() -> Vec<(String, Vec<String>)> {
    let mut files = Vec::new();
    files_under(&Path::new(ROOT).join("../src"), &mut files);
    assert!(
        files.len() > 100,
        "only {} frontend files: the scan is inert",
        files.len()
    );
    let mut uses = Vec::new();
    for f in &files {
        let text = std::fs::read_to_string(f).unwrap();
        if text.lines().any(|l| !is_comment(l) && l.contains(MODULE)) {
            let shown = f.strip_prefix(ROOT).unwrap_or(f).display().to_string();
            uses.push((shown, fs_names_in(&text)));
        }
    }
    uses
}

#[test]
fn every_fs_function_the_frontend_calls_is_allowed_by_the_capability() {
    let permissions = capability_permissions();
    let uses = fs_uses();
    assert!(
        !uses.is_empty(),
        "no frontend file uses {MODULE}: the scan is inert"
    );
    let mut refused = Vec::new();
    let mut unknown = Vec::new();
    for (file, names) in &uses {
        for name in names.iter().filter(|n| !NOT_COMMANDS.contains(&n.as_str())) {
            match FS_FUNCTIONS.iter().find(|(f, _, _)| f == name) {
                None => unknown.push(format!("{file}: {name}")),
                Some((_, command, allowed)) => {
                    if !allowed.iter().any(|a| permissions.iter().any(|p| p == a)) {
                        refused.push(format!(
                            "{file}: {name} invokes plugin:fs|{command}, which none of the capability's permissions allows (any of {allowed:?} would)"
                        ));
                    }
                }
            }
        }
    }
    assert!(
        unknown.is_empty(),
        "plugin-fs functions missing from FS_FUNCTIONS (pin each from the plugin's permission files):\n{}",
        unknown.join("\n")
    );
    assert!(
        refused.is_empty(),
        "the desktop app would refuse these calls:\n{}",
        refused.join("\n")
    );
}

#[test]
fn the_fs_functions_the_frontend_calls_are_the_pinned_set() {
    let uses = fs_uses();
    let unread: Vec<&String> = uses
        .iter()
        .filter(|(_, names)| names.is_empty())
        .map(|(file, _)| file)
        .collect();
    assert!(
        unread.is_empty(),
        "these files name {MODULE} but the scan read no function from them, so it cannot check them:\n{unread:?}"
    );
    let found: BTreeSet<&str> = uses
        .iter()
        .flat_map(|(_, names)| names.iter().map(String::as_str))
        .filter(|n| !NOT_COMMANDS.contains(n))
        .collect();
    let pinned: BTreeSet<&str> = FUNCTIONS_IN_USE.iter().copied().collect();
    assert_eq!(
        found, pinned,
        "the plugin-fs functions the frontend calls changed: update FUNCTIONS_IN_USE and FS_FUNCTIONS"
    );
    for f in FUNCTIONS_IN_USE {
        assert!(
            FS_FUNCTIONS.iter().any(|(name, _, _)| name == f),
            "{f} is pinned as in use but has no entry in FS_FUNCTIONS"
        );
    }
}

#[test]
fn no_frontend_code_invokes_an_fs_command_directly() {
    let mut files = Vec::new();
    files_under(&Path::new(ROOT).join("../src"), &mut files);
    let mut bad = Vec::new();
    for f in &files {
        let text = std::fs::read_to_string(f).unwrap();
        for (i, line) in text.lines().enumerate() {
            if !is_comment(line) && line.contains("plugin:fs|") {
                bad.push(format!(
                    "{}:{}",
                    f.strip_prefix(ROOT).unwrap_or(f).display(),
                    i + 1
                ));
            }
        }
    }
    assert!(
        bad.is_empty(),
        "call the plugin's functions, so the scan above sees the command:\n{}",
        bad.join("\n")
    );
}
