//! **Every file-system call the frontend makes is allowed by the window's
//! capability** (Research OS, Phase 5B-4a; the hand test's finding a;
//! decision 160).
//!
//! `saveTextFile` called the fs plugin's `writeTextFile`, which invokes
//! `plugin:fs|write_text_file`. The window held `fs:allow-write-file`, whose
//! permission allows `write_file`, `open` and `write` only, so every text
//! export was refused before any path was considered: the Note Creator's and
//! the Citation Manager's exports, which ship, could not write a file in the
//! desktop app from 6 Jul 2026, and no test could see it. jsdom mocks the
//! plugin, and the Rust side never reads what the frontend calls.
//!
//! These scans join the two halves, over what was TYPED: every
//! `@tauri-apps/plugin-fs` function a frontend file destructures or imports
//! (an aliased dynamic import such as `noteImages.ts`'s `fs()` included), the
//! command it invokes, and the permissions in `capabilities/*.json`.
//!
//! `FS_FUNCTIONS` is pinned BY HAND from the plugin's own files at the version
//! in `Cargo.lock` (tauri-plugin-fs 2.5.1): each function's command from
//! `dist-js/index.js`, and the permissions that allow that command from
//! `permissions/autogenerated/commands/*.toml`, `permissions/*.toml` and the
//! sets in `permissions/app.toml`. It cannot be read at test time: the
//! generated ACL manifest under `gen/` is gitignored and the registry cache
//! is not in a CI checkout. The per-directory sets under
//! `permissions/autogenerated/base-directories/` (`allow-appdata-write` and
//! the like) are deliberately NOT listed, so a capability that relied on one
//! fails here until the map is extended: red, never a silent pass.
//!
//! Only files outside tests are scanned (`.vitest.` and `.test.` are skipped,
//! as in `no_link_bypasses_the_recheck.rs`): a mock does not run in the
//! webview.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

const ROOT: &str = env!("CARGO_MANIFEST_DIR");
const MODULE: &str = "@tauri-apps/plugin-fs";

