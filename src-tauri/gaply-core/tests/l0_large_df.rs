//! **Level 0 at large df (decision 90, the Phase 4 evaluation's F3).**
//!
//! This is the one change decision 90 allows under `stats_l0`: every Level 0
//! check whose p goes through `pvalue::t_two_tailed` (the t and r families of
//! `p_consistency`) gives Could not check, with its own closed reason
//! `DfBeyondMeasuredRange`, when a df is above `pvalue::T_DF_MEASURED_MAX`
//! (1e5). That is one decade below the 2e5 where the evaluation measured the
//! engine past Level 0's 1e-9 gate. Every verdict at df ≤ 1e5 stays as it was.
//!
//! The reference is `tests/fixtures/stats_l0/p_large_df.csv`, written by
//! `make_p_large_df.R` with `/usr/local/bin/Rscript`: the evaluation's grid of
//! 13 df from 1e3 to 1e7 and 14 values of |t|, `2 * pt(|t|, df, lower.tail =
//! FALSE)`. R's p is the true p, so a printed p equal to it, rounded, must
//! never be judged Inconsistent.
//!
//! ```text
//! cargo test -p gaply_core --test l0_large_df -- --nocapture
//! ```

use gaply_core::extract::extract_from_text;
use gaply_core::stats_l0::input::{DocumentContext, L0Input};
use gaply_core::stats_l0::method::VerificationMethod;
use gaply_core::stats_l0::p_consistency::PConsistency;
use gaply_core::stats_l0::pvalue;
use gaply_core::stats_l0::result::{read_results, TableStructure};

/// Level 0's own relative gate against R (`tests/l0_p_reference.rs`).
const RELATIVE_GATE: f64 = 1e-9;

/// The limit decision 90 sets. The test names the number so a change to the
/// constant is a visible change here too.
const LIMIT: f64 = 1e5;

/// The reason's Debug form: written as text so that this file states the
/// reason it expects even where the reason does not exist yet.
const BEYOND: &str = "CouldNotCheck(DfBeyondMeasuredRange)";

fn grid() -> Vec<(f64, f64, f64)> {
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/tests/fixtures/stats_l0/p_large_df.csv"
    );
    let text = std::fs::read_to_string(path).expect("p_large_df.csv is present");
    assert!(
        text.contains("# Generated by /usr/local/bin/Rscript make_p_large_df.R"),
        "the fixture is R's"
    );
    let mut rows = Vec::new();
    let mut header = false;
    for line in text.lines().filter(|l| !l.starts_with('#')) {
        if !header {
            assert_eq!(line, "df,t,p");
            header = true;
            continue;
        }
        let f: Vec<f64> = line
            .split(',')
            .map(|x| x.parse().expect("a number"))
            .collect();
        rows.push((f[0], f[1], f[2]));
    }
    assert_eq!(rows.len(), 182, "13 df x 14 |t|");
    rows
}

/// `p` to `k` significant digits, written out in decimal.
fn decimal(p: f64, k: usize) -> String {
    let s = format!("{:.*e}", k - 1, p);
    let (mantissa, exp) = s.split_once('e').expect("exponent");
    let exp: i32 = exp.parse().expect("exp");
    let digits: String = mantissa.chars().filter(|c| c.is_ascii_digit()).collect();
    assert!(exp < 0, "every p in the grid is below 1");
    format!("0.{}{}", "0".repeat((-exp - 1) as usize), digits)
}

/// Level 0's p verdict on one printed sentence, as its Debug text; `None`
/// when the reader does not read the sentence as one result.
fn verdict(sentence: &str) -> Option<String> {
    let ex = extract_from_text(&format!("A Title\n\nResults\n{sentence}\n"));
    let reading = read_results(&ex, TableStructure::NotAvailable);
    if reading.results.len() != 1 {
        return None;
    }
    let ctx = DocumentContext::read(&ex, &reading);
    Some(format!(
        "{:?}",
        PConsistency
            .run(&L0Input {
                result: &reading.results[0],
                context: &ctx
            })
            .outcome
    ))
}

fn t_sentence(df: f64, t: f64, p: &str) -> String {
    format!("The groups differed, t({df}) = {t:.11}, p = {p}.")
}

/// Every grid row whose sentence the reader reads, at 3 and at 10 printed
/// digits of p: (df, |t|, k, verdict).
fn verdicts() -> Vec<(f64, f64, usize, String)> {
    let mut out = Vec::new();
    for (df, t, p) in grid() {
        for k in [3, 10] {
            if let Some(v) = verdict(&t_sentence(df, t, &decimal(p, k))) {
                out.push((df, t, k, v));
            }
        }
    }
    out
}

#[test]
fn the_limit_is_decision_90s_and_the_engine_meets_level_0s_gate_up_to_it() {
    assert_eq!(pvalue::T_DF_MEASURED_MAX, LIMIT);
    let mut worst_within = 0.0f64;
    let mut over_above = 0;
    for (df, t, p) in grid() {
        let g = pvalue::t_two_tailed(t, df).expect("a p");
        let rel = (g - p).abs() / p;
        if df <= LIMIT {
            assert!(
                rel <= RELATIVE_GATE,
                "df {df}, |t| {t}: {rel:e} over the 1e-9 gate inside the measured range"
            );
            worst_within = worst_within.max(rel);
        } else if rel > RELATIVE_GATE {
            over_above += 1;
        }
    }
    println!("worst relative error at df <= 1e5: {worst_within:.3e}; rows over the gate above 1e5: {over_above}");
    // The limit is where it is because the gate fails above it: if the engine
    // were fixed, this goes red and the limit may be raised (decision 90).
    assert!(
        over_above > 0,
        "the engine now meets the gate above 1e5: the limit can be reviewed"
    );
}

#[test]
fn above_df_1e5_a_t_p_could_not_be_checked_with_its_own_reason() {
    let v = verdicts();
    let above: Vec<_> = v.iter().filter(|(df, ..)| *df > LIMIT).collect();
    assert!(
        above.len() >= 100,
        "only {} sentences above 1e5 were read",
        above.len()
    );
    let wrong: Vec<_> = above.iter().filter(|(.., v)| v != BEYOND).collect();
    println!(
        "above 1e5: {} sentences, {} not {BEYOND}",
        above.len(),
        wrong.len()
    );
    assert!(
        wrong.is_empty(),
        "{} of {} sentences above df 1e5 were judged:\n{:#?}",
        wrong.len(),
        above.len(),
        &wrong[..wrong.len().min(10)]
    );
    // The evaluation's row: Inconsistent before decision 90.
    let row = verdict(&t_sentence(1e7, 1.5, &decimal(0.13361443410762952, 10)));
    assert_eq!(row.as_deref(), Some(BEYOND));
}

#[test]
fn at_df_1e5_and_below_every_verdict_is_unchanged() {
    let v = verdicts();
    let within: Vec<_> = v.iter().filter(|(df, ..)| *df <= LIMIT).collect();
    assert!(
        within.len() >= 100,
        "only {} sentences at or below 1e5 were read",
        within.len()
    );
    let not_consistent: Vec<_> = within
        .iter()
        .filter(|(.., v)| v != "Consistent(None)")
        .collect();
    assert!(not_consistent.is_empty(), "{not_consistent:#?}");
}

#[test]
fn the_boundary_is_above_1e5_and_covers_a_fractional_df_and_r() {
    // At exactly 1e5 the check runs: t = 2.0 with its true p is Consistent.
    let p = pvalue::t_two_tailed(2.0, 1e5).unwrap();
    let at = verdict(&t_sentence(1e5, 2.0, &decimal(p, 3)));
    assert_eq!(at.as_deref(), Some("Consistent(None)"));
    // A wrong p at 1e5 is still Inconsistent: the limit hides nothing below it.
    let wrong = verdict(&t_sentence(1e5, 2.0, "0.01"));
    assert!(
        wrong
            .as_deref()
            .is_some_and(|v| v.starts_with("Inconsistent")),
        "{wrong:?}"
    );
    // One above, a fractional df whose interval reaches above, and r.
    for s in [
        t_sentence(100001.0, 2.0, "0.0455"),
        "The groups differed, t(100000.4) = 2.00, p = .046.".to_string(),
        "Scores correlated, r(200000) = .0050, p = .025.".to_string(),
    ] {
        assert_eq!(verdict(&s).as_deref(), Some(BEYOND), "{s}");
    }
    // Families that do not go through the t distribution are unaffected.
    let chi = verdict("Uptake differed, χ2(1, N = 300000) = 6.90, p = .009.");
    assert_eq!(chi.as_deref(), Some("Consistent(None)"));
}
